/* Expanded built-in recipe collection.
 *
 * These recipes use the same tray as the core collection and are written for
 * two servings. They are compact on purpose: the helper keeps every entry
 * shaped exactly like a `Recipe`, while the recipe text stays easy to scan.
 *
 * Provenance and licensing are recorded on every entry through
 * `ORIGINAL_RECIPE_SOURCE`; none of these recipes are copied from a cookbook.
 */
import type { MealType, Recipe } from '../domain/types';
import { ORIGINAL_RECIPE_SOURCE } from './provenance';

type IngredientRow = readonly [ingredientId: string, amount: number];

function r(
  id: string,
  name: string,
  dishEmoji: string,
  timeMinutes: number,
  mealTypes: readonly MealType[],
  ingredients: readonly IngredientRow[],
  steps: readonly string[],
): Recipe {
  return {
    id,
    name,
    dishEmoji,
    servings: 2,
    timeMinutes,
    mealTypes: [...mealTypes],
    source: { ...ORIGINAL_RECIPE_SOURCE },
    ingredients: ingredients.map(([ingredientId, amount]) => ({ ingredientId, amount })),
    steps: [...steps],
  };
}

